//! F8 — реестр абонентов (`citadel_token::admin::parse_registry`).
//!
//! **Кто подаёт:** файл на диске издателя. В модели «сервер скомпрометирован» это ввод под
//! контролем противника напрямую; в модели «сервер честный» — файл, который админ правит руками.
//!
//! **Инвариант, который тут важнее паники:** кривая строка не должна «воскрешать» записи —
//! разбор обязан либо понять строку целиком, либо пропустить её, но никогда не отдать запись с
//! чужим `client_id` или с потерянным статусом отзыва. Первое проверяет фаззер, второе —
//! утверждение ниже.
#![no_main]

use libfuzzer_sys::fuzz_target;

fuzz_target!(|data: &[u8]| {
    let Ok(text) = std::str::from_utf8(data) else { return };
    let entries = citadel_token::admin::parse_registry(text);
    // Записей не может быть больше, чем строк: разбор не имеет права размножать записи.
    assert!(
        entries.len() <= text.lines().count(),
        "parse_registry вернул {} записей на {} строк",
        entries.len(),
        text.lines().count()
    );
    for e in &entries {
        // Статус — то, на чём держится отзыв. Пустой статус, принятый как «активна», был бы
        // ровно тем сценарием, где битая строка реестра открывает доступ отозванному абоненту.
        assert!(
            !e.status.is_empty(),
            "запись реестра с пустым статусом: отзыв держится на этом поле"
        );
    }
});
