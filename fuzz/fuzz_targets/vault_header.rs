//! F10 — заголовок и таблица слотов хранилища (`vault::probe_header`).
//!
//! **Кто подаёт:** тот, кто подменил файл: бэкап, синхронизация, сосед по устройству — и, в
//! пределе, **скомпрометированный клиент**, которому подсунули чужое хранилище.
//!
//! **Инвариант:** границы Argon2-параметров и таблицы слотов проверяются ДО криптографии, то есть
//! файл не может ни назначить себе 16 ГиБ памяти под KDF, ни заставить разбор аллоцировать по
//! своему полю длины.
#![no_main]

use libfuzzer_sys::fuzz_target;

fuzz_target!(|data: &[u8]| {
    let _ = citadel_client::vault::probe_header(data);
});
