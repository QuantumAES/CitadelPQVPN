//! F1 — разбор obfs-пакета L1 (`citadel-obfs`).
//!
//! **Кто подаёт:** кто угодно в сети (UDP/TCP-байты ДО всякой аутентификации) и, отдельно,
//! скомпрометированный exit — он знает PSK эпохи, то есть его ввод проходит AEAD-гейт и попадает
//! глубже, во внутренний разбор. Поэтому фаззатся ОБА слоя: и `open` с чужим ключом (внешний
//! путь), и `parse_inner` (то, что видит уже расшифрованный поток).
//!
//! **Инвариант:** мусор → `Err`/`None`, никогда паника и никогда аллокация по длине из пакета.
#![no_main]

use libfuzzer_sys::fuzz_target;

fuzz_target!(|data: &[u8]| {
    // Внешний слой: ключ противнику неизвестен — почти всё обязано отсекаться AEAD-гейтом.
    let psk = [0x5au8; 32];
    let _ = citadel_obfs::open(&psk, data);

    // Слой «расшифрованного»: сюда попадает то, что подал ВЛАДЕЛЕЦ ключа эпохи, то есть в модели
    // компрометации — сам exit. Разбор обязан держать любые байты.
    let _ = citadel_obfs::parse_inner(data);
});
