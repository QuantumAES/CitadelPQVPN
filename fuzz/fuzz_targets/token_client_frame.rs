//! F6 — кадры Layer-1 на стороне ИЗДАТЕЛЯ (`read_frame` + `pqid::parse_client_frame`).
//!
//! **Кто подаёт:** любой, кто дотянулся до token-порта, и в первую очередь —
//! **скомпрометированный клиент**: у него есть валидные кредиты, он проходит транспорт и obfs, и
//! всё, что он шлёт дальше, разбирает издатель. Паника здесь роняет обслуживание чужих абонентов.
//!
//! **Инвариант:** длина из кадра не диктует аллокацию (потолок проверяется до чтения тела),
//! любой CBOR-мусор → `Err`.
#![no_main]

use libfuzzer_sys::fuzz_target;

fuzz_target!(|data: &[u8]| {
    // Кадрирование: u32 BE len ‖ payload. Читаем из среза как из потока — ровно так это делает
    // издатель на принятом соединении.
    let mut cur = std::io::Cursor::new(data);
    while let Ok(body) = citadel_token::read_frame(&mut cur) {
        // Тело кадра — это и есть то, что уходит в разбор клиентского кадра.
        let _ = citadel_token::pqid::parse_client_frame(&body);
        if body.is_empty() {
            break; // пустой кадр законен; без этого цикл на нулевых длинах не двигался бы
        }
    }
    // И отдельно — сырые байты прямо в разборщик кадра, минуя кадрирование.
    let _ = citadel_token::pqid::parse_client_frame(data);
});
