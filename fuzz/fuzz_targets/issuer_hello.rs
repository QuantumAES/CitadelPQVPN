//! Кадр издателя в сторону КЛИЕНТА (`pqid::verify_hello`).
//!
//! **Кто подаёт:** скомпрометированный (или поддельный) издатель. Это единственная цель, где
//! противник — сервер, а жертва — клиент: hello разбирается ДО того, как клиент что-либо о себе
//! сообщил, и до проверки подписи. Паника здесь роняет приложение человека по вводу с сервера.
//!
//! **Инвариант:** любые байты → `Err`; успех невозможен без валидной ML-DSA-подписи под
//! коммитментом и pin'ом, которых у фаззера нет (то есть `Ok` здесь означал бы находку).
#![no_main]

use libfuzzer_sys::fuzz_target;

fuzz_target!(|data: &[u8]| {
    let commitment = [0x11u8; 32];
    let pin = [0x22u8; 32];
    let ekm = [0x33u8; 32];
    let r = citadel_token::pqid::verify_hello(data, &commitment, &pin, &ekm);
    assert!(r.is_err(), "verify_hello принял hello без подписи под фиксированным коммитментом");
});
