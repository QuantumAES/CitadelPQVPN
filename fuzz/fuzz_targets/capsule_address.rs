//! F3 — адресные капсулы и подсказка простоя (`decode_assigned_v4`, `decode_idle_hint`).
//!
//! **Кто подаёт:** exit — он назначает клиенту адрес и префикс. Скомпрометированный exit здесь
//! интересен не паникой, а **семантикой**: абсурдный префикс или адрес, принятые как есть,
//! превращаются в неверные маршруты у клиента (а `/0` в чужих руках — в перехват всего трафика).
//! Поэтому цель проверяет не только «не упало», но и границы принятых значений.
#![no_main]

use libfuzzer_sys::fuzz_target;

fuzz_target!(|data: &[u8]| {
    if let Some(a) = citadel_masque::capsule::decode_assigned_v4(data) {
        // Клиент клампит префикс отдельно (client.rs), но принимать заведомо невозможный он не
        // должен уже здесь: /33 не существует ни при каком exit'е.
        assert!(a.prefix <= 32, "decode_assigned_v4: префикс {} > 32", a.prefix);
    }
    let _ = citadel_masque::capsule::decode_idle_hint(data);
});
