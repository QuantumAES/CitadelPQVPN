import 'package:flutter/foundation.dart';

/// Видимо ли сейчас окно приложения (десктоп: скрыто в трей / свёрнуто).
///
/// **Зачем это вообще есть.** Flutter не знает, что окно спрятано: скрытое окно продолжает
/// получать такты вертикальной синхронизации, поэтому любая бесконечная анимация в дереве
/// виджетов планирует кадр за кадром и без окна на экране. У нас такая анимация ровно там, где
/// она дороже всего обходится: индикатор «Подключение…» крутится всё время, пока движок ретраит
/// недоступный сервер, — а ретраить он может часами. Живой симптом: свернули в трей, туннель не
/// поднимается, процессор занят и не освобождается.
///
/// Флаг ставит `main.dart` (там мы сами зовём `hide()`/`show()` и слушаем сворачивание), а
/// потребители используют его двумя способами:
///  * `TickerMode(enabled: …)` над всем приложением — гасит анимации (Ticker'ы) целиком;
///  * фоновые обновления (`Timer` индикации трафика, поток журнала ядра) не зовут `setState`,
///    пока окна не видно: перестроить дерево ради кадра, который никто не увидит, — чистая трата.
///
/// Сама работа движка (сессия, реконнект, kill-switch) от этого не зависит: гасится ТОЛЬКО
/// отрисовка. При возврате окна потребители догоняют состояние одним обновлением.
final ValueNotifier<bool> windowVisible = ValueNotifier<bool>(true);
