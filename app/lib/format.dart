/// Приведение технических строк ядра к виду, который показывается человеку на главном экране.
///
/// Главный экран намеренно НЕ показывает номера портов, внутренний адрес туннеля и маску подсети:
/// человеку они ничего не говорят, а вот случайный скриншот/демонстрация экрана выдают детали
/// конфигурации сервера и назначенный клиенту адрес. Всё это по-прежнему доступно там, где нужно
/// для разбора — в журнале отладки и диагностике.
library;

import 'package:app/l10n/strings.dart';

/// `host:port` → `host` (порт скрыт). Понимает IPv6-литерал в скобках (`[2001:db8::1]:4433`);
/// голый IPv6 без скобок и строку без порта возвращает как есть.
String hostOnly(String hostPort) {
  final s = hostPort.trim();
  if (s.startsWith('[')) {
    final close = s.indexOf(']');
    return close > 0 ? s.substring(1, close) : s;
  }
  final colon = s.indexOf(':');
  if (colon < 0) return s;
  // Несколько двоеточий и нет скобок — это голый IPv6-адрес, а не `host:port`.
  if (s.indexOf(':', colon + 1) >= 0) return s;
  return s.substring(0, colon);
}

/// Текущая скорость (байт/с) → короткая строка для плашки подключения: `0 Б/с`, `18 КБ/с`,
/// `1,4 МБ/с`. Один знак после запятой и только там, где он что-то значит: у сотен килобайт дробная
/// часть — визуальный шум, а строка на плашке обязана быть узкой и не «прыгать» шириной.
/// Отрицательное/NaN (счётчик мог обнулиться при перезапуске движка) показываем как ноль, а не как
/// мусор.
///
/// Единицы и десятичный разделитель берём из языка интерфейса (`rate_units`, `decimal_sep`):
/// «1,4 МБ/с» по-русски и «1.4 MB/s» по-английски — это не косметика, а то, как число читается.
String fmtRate(double bytesPerSec, Strings t) {
  final units = t('rate_units').split(',');
  final sep = t('decimal_sep');
  if (!bytesPerSec.isFinite || bytesPerSec <= 0) return '0 ${units.first}';
  var v = bytesPerSec;
  var u = 0;
  while (v >= 1024 && u < units.length - 1) {
    v /= 1024;
    u++;
  }
  // < 10 в единицах крупнее байт — один знак после запятой (1,4 МБ/с), иначе целое (18 КБ/с).
  final s = (u > 0 && v < 10)
      ? v.toStringAsFixed(1).replaceAll('.', sep)
      : v.round().toString();
  return '$s ${units[u]}';
}

/// Список `host:port` через запятую → те же хосты без портов (порядок и разделитель сохраняются).
String hostsOnly(String csv) => csv
    .split(',')
    .map((h) => hostOnly(h))
    .where((h) => h.isNotEmpty)
    .join(', ');
