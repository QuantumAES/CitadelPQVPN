///
/// НАМЕРЕННО пусто. Шаблонный `flutter_rust_bridge::setup_default_user_utils()` выставлял
/// процессу `RUST_BACKTRACE=1`, и это доезжало прямо до пользователя: FRB отдаёт ошибку в Dart
/// как `format!("{:?}", anyhow::Error)`, а `Debug` у anyhow при захваченном backtrace дописывает
/// блок `Stack backtrace:` со всеми кадрами. В диалоге вместо «Неверный мастер-пароль» человек
/// видел фразу и следом простыню адресов и имён функций ядра (то же — у «Имя профиля не может
/// быть пустым» и любого другого отказа без `Caused by:`; там, где цепочка причин есть, блок
/// оказывался за нею и его срезал разбор в UI).
///
/// Тот же вызов ставил `PanicBacktrace::setup()` — он дописывал backtrace в текст `PanicException`,
/// то есть второй канал того же самого. Диагностика от этого не пострадала: паники и полная
/// цепочка причин пишутся в журнал ядра (`api::diag`, свой panic-hook), который живёт локально и
/// включается пользователем; на экран им попадать незачем.
///
/// Плюс к делу: `std::env::set_var` в многопоточном процессе — UB (в edition 2024 он уже `unsafe`),
/// а FRB звал его из инициализации библиотеки.
