//! `citadel-vpnd` (lib) — нейтральное ядро Linux-сервисной модели (трек L).
//!
//! Здесь живёт ТОЛЬКО то, что обязаны одинаково понимать все три процесса клиента:
//!   * [`proto`] — кадры IPC (управляющий сокет `citadel-cli` → демон и приватный канал
//!     демон ↔ движок);
//!   * [`valid`] — разбор недоверенного ввода **на границе привилегий** (L2): строки от
//!     непривилегированных процессов превращаются в типизированные значения, из которых
//!     аргументы `ip`/`iptables` собираются заново — сырая строка до них не доходит;
//!   * [`plan`] — генерация правил kill-switch/IPv6-блока и маршрутов (чистые функции,
//!     тестируются без root — тот же приём, что `killswitch_rules` в `citadel-helper`).
//!
//! Привилегированное ИСПОЛНЕНИЕ (создание TUN, запуск `ip`/`iptables`, супервизия движка)
//! живёт в `src/main.rs` — его линкует только root-демон. Аналогия с Windows: `citadel-winnet`
//! (нейтральное ядро) ↔ `citadel-winsvc` (служба).
//!
//! Модель процессов (docs/LINUX-CLI.md):
//! ```text
//! citadel-cli (юзер, vault+пароль)  ──ctl.sock──▶  citadel-vpnd (root)
//!                                                        │ socketpair + SCM_RIGHTS
//!                                                        ▼
//!                                                  citadel-engine (uid citadel-vpn, без caps)
//! ```

pub mod plan;
pub mod proto;
pub mod valid;

/// Путь управляющего сокета (`citadel-cli` → демон). Каталог создаёт systemd (`RuntimeDirectory=`)
/// с правами `0750 root:citadel-vpn`; сам сокет — `0660 root:citadel-vpn` (L1).
pub const CTL_SOCKET: &str = "/run/citadel-vpn/ctl.sock";

/// Группа, членство в которой даёт право управлять туннелем. NB (L3): это доверенная группа —
/// её член может завернуть весь трафик машины в свой exit. Установщик её создаёт, но НИКОГО в неё
/// не добавляет автоматически.
pub const CTL_GROUP: &str = "citadel-vpn";

/// Системный пользователь, под которым крутится движок (недоверенный сетевой ввод, L13).
pub const ENGINE_USER: &str = "citadel-vpn";

/// Штатный путь движка (ставится установщиком рядом с демоном).
pub const ENGINE_PATH: &str = "/usr/lib/citadel-pqvpn/citadel-engine";

/// Штатный путь самого демона. Нужен не для запуска (его запускает systemd по юниту), а для
/// диагностики апгрейда: CLI сравнивает mtime этого файла со временем старта работающего
/// демона и ловит ситуацию «новый бинарь установлен, но продолжает работать старый процесс».
pub const DAEMON_PATH: &str = "/usr/lib/citadel-pqvpn/citadel-vpnd";

/// Имя TUN-интерфейса клиента. Жёстко фиксировано: `valid` не принимает имя интерфейса от
/// непривилегированной стороны вообще (иначе «удали чужой iface» через демона).
pub const TUN_NAME: &str = "citadel0";
